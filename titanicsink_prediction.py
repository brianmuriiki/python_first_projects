"""PREDICTION OF TITANIC SINKING

"""

import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report
import joblib
#Load Dataset FROM seaborn
df = sns.load_dataset('titanic')

print("First 5 rows:")
print(df.head())
#  Explore Data
print("\nInfo:")
print(df.info())

print("\nMissing Values:") #data cleaning
print(df.isnull().sum())
#Handle Missing Values

# Fill 'age' with median
df['age'].fillna(df['age'].median(), inplace=True)

# Fill 'embarked' with most frequent value
df['embarked'].fillna(df['embarked'].mode()[0], inplace=True)

# Drop 'deck' (too many missing values)
df.drop('deck', axis=1, inplace=True)
 # Drop Irrelevant Columns
df.drop(['alive', 'who', 'adult_male', 'class', 'embark_town'], axis=1, inplace=True)
#Convert Categorical Data
le = LabelEncoder()

categorical_cols = ['sex', 'embarked']

for col in categorical_cols:
    df[col] = le.fit_transform(df[col])
# Define Features & Target
X = df.drop('survived', axis=1)
y = df['survived']
#Feature Scaling
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)
#Train/Test Split
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42
)
#Train Model
model = RandomForestClassifier(n_estimators=100, random_state=42)
model.fit(X_train, y_train)
#Predictions
y_pred = model.predict(X_test)
#Evaluation
print("\nAccuracy:", accuracy_score(y_test, y_pred))

print("\nConfusion Matrix:")
print(confusion_matrix(y_test, y_pred))

print("\nClassification Report:")
print(classification_report(y_test, y_pred))

#Save Model
joblib.dump(model, "titanic_model.pkl")
print("\nModel saved as titanic_model.pkl")

