#  Import Libraries

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import fetch_california_housing
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor

from sklearn.metrics import mean_squared_error, r2_score

import joblib



# Load Dataset

data = fetch_california_housing()

# Convert to DataFrame
df = pd.DataFrame(data.data, columns=data.feature_names)
df['PRICE'] = data.target

print("First 5 rows:")
print(df.head())



#  Explore Data

print("\nDataset Info:")
print(df.info())

print("\nStatistical Summary:")
print(df.describe())



#  Visualization

plt.figure(figsize=(10, 8))
sns.heatmap(df.corr(), annot=True, cmap='coolwarm')
plt.title("Feature Correlation Heatmap")
plt.show()



#  Preprocessing

# Check missing values
print("\nMissing Values:")
print(df.isnull().sum())

# Separate features and target
X = df.drop('PRICE', axis=1)
y = df['PRICE']

# Feature scaling
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)



# STEP 6: Train/Test Split

X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.5, random_state=42
)



#  Train Model (Linear Regression)

lr_model = LinearRegression()
lr_model.fit(X_train, y_train)



# Predictions (Linear Regression)

y_pred_lr = lr_model.predict(X_test)



# STEP 9: Evaluation (Linear Regression)

print("\n--- Linear Regression Results ---")
print("MSE:", mean_squared_error(y_test, y_pred_lr))
print("R2 Score:", r2_score(y_test, y_pred_lr))



# Train Better Model (Random Forest)

rf_model = RandomForestRegressor(n_estimators=200, random_state=42)
rf_model.fit(X_train, y_train)



# Predictions (Random Forest)

y_pred_rf = rf_model.predict(X_test)



# STEP 12: Evaluation (Random Forest)

print("\n--- Random Forest Results ---")
print("MSE:", mean_squared_error(y_test, y_pred_rf))
print("R2 Score:", r2_score(y_test, y_pred_rf))



# STEP 13: Save Model

joblib.dump(rf_model, "house_price_model.pkl")
print("\nModel saved as house_price_model.pkl")



#  Test with New Data

# Example: New house data (must match feature order)
sample_data = X.iloc[0:1]  # just using first row as example
sample_scaled = scaler.transform(sample_data)

prediction = rf_model.predict(sample_scaled)
print("\nSample Prediction:", prediction)

